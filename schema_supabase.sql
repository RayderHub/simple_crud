-- 1. Crear la tabla de usuarios
CREATE TABLE IF NOT EXISTS public.usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    rol TEXT NOT NULL DEFAULT 'Usuario' CHECK (rol IN ('Administrador', 'Editor', 'Usuario')),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Índice para acelerar búsquedas por correo electrónico
CREATE INDEX IF NOT EXISTS idx_usuarios_email ON public.usuarios (email);

-- 3. Desactivar RLS para permitir conexión directa desde el backend Flask
-- (Si prefieres usar RLS en producción, habilítalo y usa la service_role key en el backend)
ALTER TABLE public.usuarios DISABLE ROW LEVEL SECURITY;

